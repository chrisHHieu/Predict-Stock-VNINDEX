"""Optuna tuning for LightGBM.

Protocol
--------
The search uses five expanding-window validation blocks that all end at or
before ``model.walk_forward.min_train_rows`` (500 rows). That region is the
*initial* training window of the backtest, so tuning never sees the 252-row
holdout or a single walk-forward test row. The objective is mean log-loss over
the five blocks, reported after every block so ``MedianPruner`` can stop a bad
trial early.

The study is persisted in ``reports/optuna.db`` (SQLite) and the winning
parameters are written to ``configs/tuned.yaml`` with the rest of the config
unchanged.
"""

from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import yaml
from sklearn.metrics import log_loss

from vnindex_forecast.config import AppConfig
from vnindex_forecast.features.build import feature_columns, load_or_build_features
from vnindex_forecast.models import registry
from vnindex_forecast.models.factory import build_classifier


@dataclasses.dataclass
class TuneResult:
    best_value: float
    best_params: dict[str, Any]
    trials: int
    pruned: int
    output_path: Path
    windows: list[dict[str, str]]


def validation_windows(
    features: pd.DataFrame, config: AppConfig
) -> list[tuple[pd.DataFrame, pd.DataFrame]]:
    """Expanding train / fixed validation blocks inside the initial train window."""
    names = feature_columns(config)
    frame = features.sort_values("date").reset_index(drop=True)
    frame = frame.dropna(subset=names + ["direction", "next_return"]).reset_index(drop=True)

    settings = config.model.tuning
    end = config.model.walk_forward.min_train_rows
    block_rows = settings.block_rows
    blocks = settings.blocks
    first_end = max(settings.warmup_rows + block_rows, end - block_rows * blocks)
    step = max(block_rows, (end - first_end) // max(blocks - 1, 1))
    ends = [first_end + step * index for index in range(blocks)]
    ends[-1] = min(ends[-1], end)

    windows = []
    for stop in ends:
        start = max(0, stop - block_rows)
        train = frame.iloc[:start]
        valid = frame.iloc[start:stop]
        if len(train) < 30 or valid["direction"].nunique() < 2:
            continue
        windows.append((train, valid))
    if not windows:
        raise ValueError("no usable tuning window inside the initial training range")
    return windows


def _objective(trial: Any, windows, config: AppConfig, names: list[str]) -> float:
    params = {
        "num_leaves": trial.suggest_int("num_leaves", 7, 63, log=True),
        "learning_rate": trial.suggest_float("learning_rate", 0.01, 0.20, log=True),
        "min_child_samples": trial.suggest_int("min_child_samples", 10, 80),
        "reg_lambda": trial.suggest_float("reg_lambda", 1e-3, 10.0, log=True),
        "colsample_bytree": trial.suggest_float("colsample_bytree", 0.5, 1.0),
    }
    local = config.model_copy(deep=True)
    for key, value in params.items():
        setattr(local.model, key, value)

    scores: list[float] = []
    for step, (train, valid) in enumerate(windows):
        model = build_classifier(local, names)
        model.fit(train[names], train["direction"].astype(int))
        probabilities = model.predict_proba(valid[names])[:, 1]
        scores.append(
            float(log_loss(valid["direction"].astype(int), probabilities, labels=[0, 1]))
        )
        trial.report(float(np.mean(scores)), step)
        if trial.should_prune():
            import optuna

            raise optuna.TrialPruned()
    return float(np.mean(scores))


def _write_tuned_config(
    config: AppConfig, params: dict[str, Any], result_meta: dict[str, Any], output: Path
) -> None:
    payload = config.as_dict()
    payload["model"].update(params)
    header = [
        "# Generated by `python -m vnindex_forecast tune`.",
        f"# Date: {result_meta['generated_at']}",
        f"# Trials: {result_meta['trials']}, best log-loss: "
        f"{result_meta['best_value']:.6f}",
        "# Validation: expanding blocks inside the first 500 rows "
        "(no holdout, no walk-forward test).",
        "",
    ]
    body = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(header) + body, encoding="utf-8")


def tune(
    config: AppConfig,
    trials: int | None = None,
    output: str | Path | None = None,
    study_name: str = "vnindex_lightgbm",
) -> TuneResult:
    """Run the search and write ``configs/tuned.yaml``."""
    import optuna

    features = load_or_build_features(config)
    names = feature_columns(config)
    windows = validation_windows(features, config)
    trial_count = int(trials if trials is not None else config.model.tuning.trials)
    if trial_count < 1:
        raise ValueError("trials must be at least 1")

    reports_dir = config.path("reports_dir")
    reports_dir.mkdir(parents=True, exist_ok=True)
    storage = f"sqlite:///{(reports_dir / 'optuna.db').as_posix()}"
    sampler = optuna.samplers.TPESampler(seed=config.model.tuning.sampler_seed, multivariate=True)
    pruner = optuna.pruners.MedianPruner(
        n_startup_trials=max(3, trial_count // 3),
        n_warmup_steps=2,
        interval_steps=1,
    )
    study = optuna.create_study(
        study_name=study_name,
        storage=storage,
        direction="minimize",
        sampler=sampler,
        pruner=pruner,
        load_if_exists=True,
    )
    study.optimize(
        lambda trial: _objective(trial, windows, config, names),
        n_trials=trial_count,
        gc_after_trial=True,
    )

    output_path = Path(output) if output is not None else Path("configs") / "tuned.yaml"
    if not output_path.is_absolute():
        from vnindex_forecast.config import REPO_ROOT

        output_path = REPO_ROOT / output_path
    meta = {
        "generated_at": registry.utc_now(),
        "trials": len(study.trials),
        "best_value": float(study.best_value),
        "config_hash_before": config.hash(),
        "windows": [
            {
                "valid_start": str(pd.Timestamp(valid["date"].min()).date()),
                "valid_end": str(pd.Timestamp(valid["date"].max()).date()),
                "train_rows": int(len(train)),
                "valid_rows": int(len(valid)),
            }
            for train, valid in windows
        ],
    }
    _write_tuned_config(config, study.best_params, meta, output_path)
    study.trials_dataframe().to_csv(reports_dir / "tuning_trials.csv", index=False)
    (reports_dir / "tuning.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    return TuneResult(
        best_value=float(study.best_value),
        best_params=dict(study.best_params),
        trials=len(study.trials),
        pruned=sum(trial.state.name == "PRUNED" for trial in study.trials),
        output_path=output_path,
        windows=meta["windows"],
    )
